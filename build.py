#!/usr/bin/env python3
"""Build the Teeology PWA into dist/.

dist/index.html             single self-contained page (CSS + engine + app inlined)
dist/manifest.webmanifest   install metadata (home-screen app on iPhone and Android)
dist/sw.js                  service worker: works offline on the course
dist/*.png                  icons (from assets/, made by tools/make_icons.py)
"""
import hashlib
import json
import pathlib
import shutil

root = pathlib.Path(__file__).parent
src, assets, dist = root / "src", root / "assets", root / "dist"
css = (src / "app.css").read_text()
engine = (src / "engine.js").read_text()
app = (src / "app.js").read_text()

html = f"""<!DOCTYPE html>
<html lang="en-GB">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="#1F4D3A">
<meta name="description" content="Teeology: reach the zone, get down. Golf scoring and stats against your net par.">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="Teeology">
<title>Teeology</title>
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" sizes="192x192" href="icon-192.png">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;600;700&family=Space+Grotesk:wght@600;700&display=swap" rel="stylesheet">
<style>
{css}
</style>
</head>
<body>
<div id="app"></div>
<script>
{engine}
</script>
<script>
{app}
</script>
</body>
</html>
"""

manifest = {
    "name": "Teeology",
    "short_name": "Teeology",
    "description": "Reach the zone, get down. Golf scoring and stats against your net par.",
    "start_url": "./",
    "scope": "./",
    "display": "standalone",
    "orientation": "portrait",
    "background_color": "#F6F4EE",
    "theme_color": "#1F4D3A",
    "icons": [
        {"src": "icon-192.png", "sizes": "192x192", "type": "image/png"},
        {"src": "icon-512.png", "sizes": "512x512", "type": "image/png"},
        {"src": "icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
    ],
}

icons = ["icon-192.png", "icon-512.png", "icon-maskable-512.png", "apple-touch-icon.png"]
version = hashlib.sha256((html + json.dumps(manifest)).encode()).hexdigest()[:12]
precache = ["./", "index.html", "manifest.webmanifest"] + icons

sw = f"""// Teeology service worker (generated by build.py). Version {version}
const CACHE = 'teeology-{version}';
const PRECACHE = {json.dumps(precache)};
self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('teeology-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', e => {{
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // The app page: network first so updates arrive, cache when there's no signal.
  if (req.mode === 'navigate') {{
    e.respondWith(fetch(req).then(r => {{ const copy = r.clone(); caches.open(CACHE).then(c => c.put('index.html', copy)); return r; }})
      .catch(() => caches.match('index.html')));
    return;
  }}
  // Same-origin files and Google Fonts: cache first, fill the cache on first use.
  if (url.origin === location.origin || /fonts\\.(googleapis|gstatic)\\.com$/.test(url.hostname)) {{
    e.respondWith(caches.match(req).then(hit => hit || fetch(req).then(r => {{
      if (r.ok || r.type === 'opaque') {{ const copy = r.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }}
      return r;
    }})));
  }}
}});
"""

dist.mkdir(exist_ok=True)
(dist / "index.html").write_text(html)
(dist / "manifest.webmanifest").write_text(json.dumps(manifest, indent=2))
(dist / "sw.js").write_text(sw)
for name in icons:
    shutil.copy(assets / name, dist / name)
print(f"dist/ built (version {version}): index.html {len(html)} bytes, sw.js, manifest, {len(icons)} icons")
